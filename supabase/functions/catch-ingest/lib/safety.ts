/**
 * Предфильтр кризисных маркеров (safety-guardian, «Протокол кризиса»).
 *
 * Это НЕ замена скиллу safety-guardian — модель, читающая запись при
 * толковании, обязана проходить полный протокол сама. Здесь — дешёвая
 * проверка на входе, до всякой генерации: если она сработала, толкование
 * не запускается вообще и разговор уходит в кризисный сценарий раньше,
 * чем модель успеет прочитать текст как «символ».
 *
 * Ложные срабатывания здесь безопаснее пропуска: цена ошибки — лишний
 * человеческий контакт, а не пропущенный кризис.
 */

export type CrisisMarker =
  | 'suicidal_ideation'
  | 'self_harm'
  | 'violence'
  | 'derealization'
  | 'hopelessness';

const MARKERS: Record<CrisisMarker, RegExp> = {
  // Суицидальные мысли: намерение, способ, прощание.
  suicidal_ideation:
    /(покончить с собой|суицид|не хочу жить|хочу умереть|уйти из жизни|свести счёты с жизнью)/i,
  // Самоповреждение.
  self_harm: /(режу себя|порезал(ся|а)?|наношу себе|причин(яю|ил|ила) себе боль)/i,
  // Насилие — к себе или от других, в адрес себя.
  violence: /(избил(и)?( меня)?|изнасиловал|угрожа(ет|ли).{0,20}(убить|расправ)|избивает меня)/i,
  // Острая дереализация.
  derealization: /(не чувствую (что )?реальность|как будто (я )?не в своём теле|мир ненастоящий|отделился(ась)? от тела)/i,
  // Отчаяние без просвета.
  hopelessness: /(нет смысла жить|всё бессмысленно и так будет всегда|никогда не станет лучше)/i,
};

export interface CrisisScanResult {
  triggered: boolean;
  markers: CrisisMarker[];
}

export function scanCrisisMarkers(text: string): CrisisScanResult {
  const markers = (Object.keys(MARKERS) as CrisisMarker[]).filter((key) => MARKERS[key].test(text));
  return { triggered: markers.length > 0, markers };
}

/**
 * Маркеры магического мышления (safety-guardian, «Протокол магического
 * мышления»). Порог «3+ записи» считается вызывающей стороной по истории
 * пользователя — здесь только детекция в одной записи.
 */
const MAGICAL_THINKING = /(это (был )?знак|вселенная (мне )?отвечает|приложение предсказало|это неспроста)/i;

export function looksLikeMagicalThinking(text: string): boolean {
  return MAGICAL_THINKING.test(text);
}
